// Tenant registry for the drift system: which Hadrius company a walkthrough was recorded in, and which
// dedicated automation account / Keychain item / browser profile replays it.
//
// Import-safe: no side effects, reads no secrets. The Keychain item named here is read only by
// academy-login.mjs at sign-in time.
//
// CLI:
//   node tools/drift/tenants.mjs --survey                 (tenant counts over scripts/*.script.json)
//   node tools/drift/tenants.mjs --allowlist [--write]    (regenerate tools/drift/allowlist.json)
import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs';
import {join,resolve,dirname,basename} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {loadTenantEvidence,evidenceMatches} from './tenant-evidence.mjs';

export const REPO=resolve(dirname(fileURLToPath(import.meta.url)),'..','..');
export const APP_ORIGIN='https://app.hadrius.com';

export const TENANTS=Object.freeze({
  academy:Object.freeze({key:'academy',companyId:1150,name:'Hadrius Academy',account:'stephen+hstudio@hadrius.com',
    keychainService:'hadrius-studio-academy',profileDir:'.browser-profile-drift',startPath:'/marketing/projects'}),
  sandbox:Object.freeze({key:'sandbox',companyId:1048,name:'Hadrius Sandbox',account:'stephen+hsandbox@hadrius.com',
    keychainService:'hadrius-studio-sandbox',profileDir:'.browser-profile-drift-sandbox',startPath:'/marketing/projects'}),
});
export const DEFAULT_TENANT='academy';
export const TENANT_KEYS=Object.freeze(Object.keys(TENANTS));

/** Registry entry by key (or an entry object passed through). Unknown keys throw: never guess a tenant. */
export function getTenant(key=DEFAULT_TENANT){
  if(key&&typeof key==='object'&&TENANTS[key.key]===key)return key;
  const t=TENANTS[String(key)];if(!t)throw new Error(`unknown_tenant:${key}`);return t;}
export function tenantForCompanyId(id){if(id==null||id==='')return null;return Object.values(TENANTS).find(t=>String(t.companyId)===String(id))??null;}
export const tenantProfileDir=(key,repo=REPO)=>join(repo,getTenant(key).profileDir);
export const tenantStartUrl=(key)=>{const t=getTenant(key);return `${APP_ORIGIN}${t.startPath}?company_id=${t.companyId}`;};
/** Tenant whose dedicated profile this directory is (by basename), or null (AI-slot / other profiles). */
export function tenantForProfile(dir){const b=basename(String(dir??''));return Object.values(TENANTS).find(t=>t.profileDir===b)??null;}

function companyIdIn(url){if(!url||typeof url!=='string')return null;try{const v=new URL(url,APP_ORIGIN).searchParams.get('company_id');return v&&/^\d+$/.test(v)?v:null;}catch{return null;}}
/** Every company_id named by the script: environment.startUrl plus each step's url/value(navigate)/route. */
export function scriptCompanyIds(script){
  const ids=new Set();const add=(u)=>{const c=companyIdIn(u);if(c)ids.add(c);};
  add(script?.environment?.startUrl);
  for(const s of script?.steps??[]){add(s?.url);if(s?.action==='navigate')add(s?.value);if(typeof s?.route==='string')add(s.route);}
  return [...ids].sort((a,b)=>Number(a)-Number(b));
}
/** -> {tenant:'academy'|'sandbox'|null, status:'ok'|'unknown'|'conflict'|'unregistered', companyIds, reason}
 *  unknown = no company_id anywhere (never guessed); conflict = more than one company; unregistered = one company
 *  that is not in the registry. Only status 'ok' may be replayed. */
export function detectScriptTenant(script,{evidence=null}={}){
  const companyIds=scriptCompanyIds(script);
  if(!companyIds.length){
    // No company in any URL: only recording-bound evidence of the company the video was RECORDED in may assign one
    // (tenant-evidence.mjs: the recorded company switcher on >=2 frames, production URLs only). Never guessed.
    const e=(evidence??loadTenantEvidence())[script?.name];
    if(evidenceMatches(e,script))return {tenant:e.tenant,status:'ok',companyIds,source:'recorded_frames',reason:`no company_id in any URL; ${e.reason} (tenant-evidence.json)`};
    return {tenant:null,status:'unknown',companyIds,reason:'no company_id in environment.startUrl or any step URL'};
  }
  if(companyIds.length>1)return {tenant:null,status:'conflict',companyIds,reason:`script names several companies: ${companyIds.join(', ')}`};
  const t=tenantForCompanyId(companyIds[0]);
  if(!t)return {tenant:null,status:'unregistered',companyIds,reason:`company ${companyIds[0]} has no automation tenant`};
  return {tenant:t.key,status:'ok',companyIds,reason:`company_id=${t.companyId}`};
}

/** Allowlist object from scripts: {schema:2, generatedAt, counts, academy:[...], sandbox:[...], unknown:[...], conflict:[...], unregistered:[...]}.
 *  Weekly runs read academy+sandbox only (weekly.mjs parseNames); unknown/conflict/unregistered are listed, never run. */
export function buildAllowlist(scripts,{now=new Date(),retired=readRetired()}={}){
  const out={schema:2,generatedAt:now.toISOString(),note:'Generated by node tools/drift/tenants.mjs --allowlist --write. Weekly runs use academy + sandbox; unknown/conflict/unregistered/retired are reported, never replayed.',
    counts:{},...Object.fromEntries(TENANT_KEYS.map(k=>[k,[]])),unknown:[],conflict:[],unregistered:[],retired:[]};
  const retiredBy=new Map((retired??[]).map(r=>[r.name,r]));
  for(const s of [...scripts].sort((a,b)=>String(a.name).localeCompare(String(b.name)))){
    if(!s?.name||String(s.name).startsWith('_studio'))continue;
    const d=detectScriptTenant(s);const row={name:s.name,title:s.title??null,company_ids:d.companyIds,steps:(s.steps??[]).length};
    const r=retiredBy.get(s.name);
    if(r){out.retired.push({...row,reason:r.reason??'retired',...(r.replacedBy?{replacedBy:r.replacedBy}:{})});continue;}
    if(d.status==='ok')out[d.tenant].push({...row,company_id:String(getTenant(d.tenant).companyId),...(d.source?{tenant_source:d.source}:{})});else out[d.status].push({...row,reason:d.reason});
  }
  for(const k of [...TENANT_KEYS,'unknown','conflict','unregistered','retired'])out.counts[k]=out[k].length;
  return out;
}
/** tools/drift/retired.json: permanent, per-video retirements (duplicates/superseded). Unreadable => none retired. */
export function readRetired(file=join(REPO,'tools','drift','retired.json')){
  if(!existsSync(file))return [];
  try{const j=JSON.parse(readFileSync(file,'utf8'));return Array.isArray(j?.videos)?j.videos.filter(v=>typeof v?.name==='string'):[];}catch{return [];}
}
export function readLocalScripts(dir=join(REPO,'scripts')){
  if(!existsSync(dir))return [];
  return readdirSync(dir).filter(f=>f.endsWith('.script.json')&&!f.startsWith('_studio')).map(f=>{try{return JSON.parse(readFileSync(join(dir,f),'utf8'));}catch{return null;}}).filter(Boolean);
}

export function main(args=process.argv.slice(2)){
  const scripts=readLocalScripts();
  if(args.includes('--survey')){const a=buildAllowlist(scripts);console.log(JSON.stringify({total:scripts.length,counts:a.counts},null,2));return a;}
  if(args.includes('--allowlist')){const a=buildAllowlist(scripts);
    if(args.includes('--write'))writeFileSync(join(REPO,'tools','drift','allowlist.json'),JSON.stringify(a,null,2)+'\n');
    console.log(JSON.stringify({counts:a.counts,written:args.includes('--write')},null,2));return a;}
  console.error('usage: tenants.mjs --survey | --allowlist [--write]');process.exitCode=64;return null;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)main();
